export function getSceneObjectCatalogItem(
  catalogId: string
): SceneObjectCatalogItem | undefined {
  return V5_SCENE_OBJECT_CATALOG.find((item) => item.catalogId === catalogId);
}

export function createSceneObjectInstanceFromCatalog(
  catalogId: string,
  overrides?: Partial<SceneObjectInstance>
): SceneObjectInstance | null {
  const item = getSceneObjectCatalogItem(catalogId);
  if (!item) return null;
  const uid = `sobj_${Date.now()}_${Math.random().toString(36).slice(2, 7)}`;

  return {
    id: uid,
    catalogId: item.catalogId,
    sku: item.sku,
    name: item.name,
    brand: item.brand,
    category: item.category,
    anchorMode: item.anchorMode,
    visualKind: item.visualKind,
    position: {
      x: 600,
      y: item.defaultElevationY ?? 0,
      z: item.anchorMode === "free_floor" ? 1350 : 0,
    },
    rotation: { x: 0, y: 0, z: 0 },
    dimensions: { ...item.defaultDimensions },
    scaleFactor: 1,
    primaryColorHex: item.primaryColorHex,
    secondaryColorHex: item.secondaryColorHex,
    metalness: item.metalness,
    roughness: item.roughness,
    glbUrl: item.glbUrl,
    commercialRole: item.commercialRole,
    unitPriceEur: item.unitPriceEur,
    quantity: 1,
    clearance: item.clearance ? { ...item.clearance } : undefined,
    cutoutTrigger: item.cutoutTrigger ? { ...item.cutoutTrigger } : undefined,
    mepTriggers: item.mepTriggers ? item.mepTriggers.map((m) => ({ ...m })) : undefined,
    lightEmission: item.lightEmission ? { ...item.lightEmission } : undefined,
    ...overrides,
  };
}

